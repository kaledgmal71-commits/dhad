// بند ١-٤ من سجل النواقص: القوالب النصية قالب"…{تعبير}…" (المطابقة مع مرمز ضاد في selfhost-lexer).
const R = require('../site/run.js'); const api = R.api;
let pass = 0, fail = 0;
const check = (n, g, w) => { if (JSON.stringify(g) === JSON.stringify(w)) pass++; else { fail++; console.log('اختلاف:', n, g, w); } };
const run = src => { try { const c = api.compile(api.parse(src)); const o = []; const vm = new api.VM({ maxSteps: 1e6, maxMs: 2000, onPrint: l => o.push(String(l)) }); vm.run(c.mainChunkIndex, c.functionChunks); return o.join('|'); } catch (e) { return 'ERR ' + e.message; } };
check('متغير', run('متغير س = "ضاد"\nاطبع(قالب"أهلًا {س}")'), 'أهلًا ضاد');
check('حساب', run('اطبع(قالب"{٢ * ٣} و {١ + ١}")'), '٦ و ٢');
check('قائمة وخريطة', run('اطبع(قالب"{[١، ٢]} {{"أ": ٣}}")'), '[١، ٢] {أ: ٣}');
check('نص داخل التعبير بقوسين', run('اطبع(قالب"{"}" + "{"}")'), '}{');
check('استدعاء دالة', run('دالة م(ع) { ارجع ع * ع }\nاطبع(قالب"مربع ٤ = {م(٤)}")'), 'مربع ٤ = ١٦');
check('هروب القوس', run('اطبع(قالب"\\{لا\\} {١}")'), '{لا} ١');
check('تعبير وحيد يعطي نصًا', run('اطبع(نوع(قالب"{٥}"))'), 'نص');
check('بلا تعابير', run('اطبع(قالب"فقط نص")'), 'فقط نص');
check('متداخل', run('متغير س = ٧\nاطبع(قالب"[{قالب"<{س}>"}]")'), '[<٧>]');
check('اسم نص كمتغير لا يكسر القالب', run('متغير نص = ٥\nاطبع(قالب"{نص}")'), '٥');
check('نص عادي فيه أقواس لا يتغير', run('اطبع("{س}")'), '{س}');
check('قالب كمعرّف عادي', run('متغير قالب = ٣\nاطبع(قالب + ١)'), '٤');
check('فارغ', run('اطبع(قالب"{}")'), 'ERR السطر 1: تعبير فارغ داخل القالب {}');
check('غير مغلق', run('اطبع(قالب"{س")'), 'ERR السطر 1: تعبير القالب غير مغلق (نسيت })');
check('خطأ داخلي', run('اطبع(قالب"{0x}")'), 'ERR السطر 1: في تعبير القالب: السطر 1: رقم بالأساس 16 بلا أرقام بعد 0x');
check('متغير غير معرّف يبلغ بسطره', run('اطبع(١)\nاطبع(قالب"{غائب}")'), 'ERR السطر 2: متغير غير معرّف: غائب');
console.log(`pass ${pass} fail ${fail}`); process.exit(fail ? 1 : 0);
