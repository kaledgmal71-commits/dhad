// نواتا تبديل المحاور وجمع المحور: مطابقة بالبت لحلقات ضاد الأصلية (محفوظة هنا) على أشكال ومحاور متنوعة
const R=require('../site/run.js');
let pass=0,fail=0;const ok=(c,m)=>{if(c)pass++;else{fail++;console.log('FAIL',m)}};
const AR=s=>String(s).replace(/\d/g,d=>'٠١٢٣٤٥٦٧٨٩'[d]);
const PRE=`
متغير م = استورد("ضاد/مصفوفات")
متغير ر = استورد("ضاد/رياضيات")
متغير غ = ر.مولّد(٦١)
دالة جمع_قديم(ب، خارج، ن، داخل) {
    متغير خرج = []
    من_أجل (أ٠ من ٠ إلى خارج - ١) {
        من_أجل (د من ٠ إلى داخل - ١) {
            متغير ج = ٠
            من_أجل (ك من ٠ إلى ن - ١) { ج = ج + ب[(أ٠ * ن + ك) * داخل + د] }
            أضف(خرج، ج)
        }
    }
    ارجع خرج
}
# تبديل بالتعريف: ناتج[فهرس ي₀…] = أصل[فهرس بحسب المحاور]
دالة تبديل_قديم(أ، محاور) {
    متغير ش = أ["شكل"]
    متغير ن = طول(ش)
    متغير خطوات = []
    من_أجل (ي من ٠ إلى ن - ١) { أضف(خطوات، ٠) }
    متغير جار = ١
    من_أجل (ي من ٠ إلى ن - ١) { خطوات[ن - ١ - ي] = جار; جار = جار * ش[ن - ١ - ي] }
    متغير ش٢ = []
    متغير خ٢ = []
    من_أجل (ي من ٠ إلى ن - ١) { أضف(ش٢، ش[محاور[ي]]); أضف(خ٢، خطوات[محاور[ي]]) }
    متغير حجم = ١
    من_أجل (ع في ش) { حجم = حجم * ع }
    متغير خرج = []
    من_أجل (ك من ٠ إلى حجم - ١) {
        متغير باقي = ك
        متغير موضع = ٠
        من_أجل (ي من ٠ إلى ن - ١) {
            متغير بعد = ن - ١ - ي
            متغير ف = باقي % ش٢[بعد]
            باقي = (باقي - ف) / ش٢[بعد]
            موضع = موضع + ف * خ٢[بعد]
        }
        أضف(خرج، أ["بيانات"][موضع])
    }
    ارجع {"بيانات": خرج، "شكل": ش٢}
}
`;
const sums=[[[5,7],0],[[5,7],1],[[3,4,5],1],[[3,4,5],-1],[[2,3,2,4],2],[[6],0]];
for(const [sh,ax] of sums){const r=R.run(PRE+`
متغير أ = م.عشوائي_طبيعي([${sh.map(AR).join('،')}]، غ، ٥)
متغير ح = ${AR(ax<0?ax+sh.length:ax)}
متغير خارج = ١
متغير داخل = ١
من_أجل (ي من ٠ إلى طول(أ["شكل"]) - ١) { إذا (ي < ح) { خارج = خارج * أ["شكل"][ي] } وإلا إذا (ي > ح) { داخل = داخل * أ["شكل"][ي] } }
متغير ن١ = م.مجموع(أ، ${ax<0?'-'+AR(-ax):AR(ax)}، خطأ)
متغير ق = جمع_قديم(أ["بيانات"]، خارج، أ["شكل"][ح]، داخل)
متغير سليم = (طول(ق) == طول(ن١["بيانات"]))
من_أجل (ي من ٠ إلى طول(ق) - ١) { إذا (ق[ي] != ن١["بيانات"][ي]) { سليم = خطأ } }
اطبع(سليم، نص(م.مجموع(أ، ${ax<0?'-'+AR(-ax):AR(ax)}، صحيح)["شكل"]))`,{maxMs:60000});
 ok(r.ok&&r.out[0].startsWith('صحيح'),`مجموع بالبت ${JSON.stringify(sh)} محور ${ax} ${JSON.stringify(r).slice(0,160)}`)}
{const r=R.run(PRE+`متغير أ = م.عشوائي_طبيعي([٣، ٤]، غ، ١)\nمتغير س = م.مجموع(أ، لاشيء، خطأ)\nمتغير ج = ٠\nمن_أجل (ع في أ["بيانات"]) { ج = ج + ع }\nاطبع(س["بيانات"][٠] == ج، نص(س["شكل"]))`,{});ok(r.ok&&r.out[0]==='صحيح []','مجموع كلي بالبت '+JSON.stringify(r))}
const perms=[[[3,4],[1,0]],[[2,3,4],[2,1,0]],[[2,3,4],[1,2,0]],[[2,3,4],[0,2,1]],[[2,3,2,4],[3,1,0,2]],[[5],[0]]];
for(const [sh,pm] of perms){const r=R.run(PRE+`
متغير أ = م.عشوائي_طبيعي([${sh.map(AR).join('،')}]، غ، ٣)
متغير ن١ = م.بدّل_محاور(أ، [${pm.map(AR).join('،')}])
متغير ق = تبديل_قديم(أ، [${pm.map(AR).join('،')}])
متغير سليم = (نص(ن١["شكل"]) == نص(ق["شكل"])) و (طول(ق["بيانات"]) == طول(ن١["بيانات"]))
من_أجل (ي من ٠ إلى طول(ق["بيانات"]) - ١) { إذا (ق["بيانات"][ي] != ن١["بيانات"][ي]) { سليم = خطأ } }
اطبع(سليم)`,{maxMs:60000});ok(r.ok&&r.out[0]==='صحيح',`تبديل بالبت ${JSON.stringify(sh)}→${JSON.stringify(pm)} ${JSON.stringify(r).slice(0,160)}`)}
// منقول مرتين = الأصل، ومحور غير صالح يرمي خطأ
{const r=R.run(PRE+`متغير أ = م.عشوائي_طبيعي([٣، ٤، ٢]، غ، ١)\nمتغير ب = م.منقول(م.منقول(أ))\nمتغير سليم = (نص(ب["بيانات"]) == نص(أ["بيانات"]))\nاطبع(سليم)`,{});ok(r.ok&&r.out[0]==='صحيح','منقول مرتين '+JSON.stringify(r).slice(0,150))}
ok(!R.run(PRE+'م.بدّل_محاور(م.أنشئ([٢، ٢]، ١)، [٠، ٥])',{}).ok,'محور غير صالح');
ok(!R.run('نواة_تبديل([١، ٢]، [٣]، [١])',{}).ok,'عدد عناصر لا يطابق الشكل');
console.log('pass',pass,'fail',fail);process.exit(fail?1:0);
