// المحلل الصرفي: دقة على مجموعة مرجعية مقسومة (ضبط/اختبار)، وبنية النتائج، والمبنيات، والمعجم، والحتمية
const R=require('../site/run.js');
const g=require('./data/morph-gold.json');
let pass=0,fail=0;const ok=(c,m)=>{if(c)pass++;else{fail++;console.log('FAIL',m)}};
const AR='٠١٢٣٤٥٦٧٨٩';const num=s=>Number(String(s).replace(/[٠-٩]/g,d=>AR.indexOf(d)).replace(/٫/g,'.'));
const run=(src,o={})=>{const r=R.run(src,{maxMs:200000,maxSteps:900000000,...o});if(!r.ok)throw new Error(JSON.stringify(r).slice(0,300));return r.out};
const ev=(words)=>{
  const src=`متغير ص = استورد("ضاد/نواة_صرف")\n`+words.map(([w])=>`من_أجل (أ في ص.حلّل("${w}"، {"أقصى": ٣})) { اطبع(نص(أ["جذر"])) }\nاطبع("#")`).join('\n');
  const o=run(src);const gr=[[]];o.forEach(x=>{if(x==='#')gr.push([]);else gr[gr.length-1].push(x)});
  let t1=0,t3=0;const bad=[];words.forEach(([w,root],i)=>{if(gr[i][0]===root)t1++;else bad.push(w+'→'+gr[i].join('/'));if(gr[i].includes(root))t3++});
  return {t1,t3,n:words.length,bad};
};
for(const sp of ['dev','test']){
  const r=ev(g[sp]);
  ok(r.t1/r.n>=0.93,`دقة أفضل تحليل (${sp}) ${r.t1}/${r.n} أخطاء: ${r.bad.join(' ')}`);
  ok(r.t3/r.n>=0.96,`دقة أفضل ٣ (${sp}) ${r.t3}/${r.n}`);
}
// بنية النتائج
{
  const o=run(`
متغير ص = استورد("ضاد/نواة_صرف")
متغير ح = ص.حلّل("المكتوب"، لاشيء)
اطبع(طول(ح))
متغير مج = ٠
من_أجل (أ في ح) { مج = مج + أ["ثقة"] }
اطبع(مج)
متغير مرتب = صحيح
من_أجل (ي من ١ إلى طول(ح) - ١) { إذا (ح[ي]["ثقة"] > ح[ي - ١]["ثقة"]) { مرتب = خطأ } }
اطبع(مرتب)
اطبع(ح[٠]["بادئة"]) اطبع(ح[٠]["جذع"]) اطبع(ح[٠]["لاحقة"]) اطبع(ح[٠]["جذر"]) اطبع(ح[٠]["وزن"])
اطبع(نص(ص.أفضل("من"، لاشيء)["نوع"]))
اطبع(نص(ص.أفضل("من"، لاشيء)["جذر"]))
اطبع(نص(ص.أفضل("مِنْ"، لاشيء)["وزن"]))
اطبع(نص(ص.حلّل(""، لاشيء)))
اطبع(نص(ص.أفضل("ب"، لاشيء)))
اطبع(طول(ص.حلّل("المكتوب"، {"أقصى": ١})))
اطبع(ص.أفضل("قال"، لاشيء)["جذر"])
اطبع(نص(ص.حلّل("مَكْتُوبٌ"، لاشيء)[٠]["جذر"]))
اطبع(نص(ص.حلّل("الْكِتَابُ"، لاشيء)[٠]["جذر"]))
`);
  ok(num(o[0])>=1,'عدد التحليلات');ok(Math.abs(num(o[1])-1)<1e-9,'مجموع الثقة ١: '+o[1]);ok(o[2]==='صحيح','الترتيب تنازلي');
  ok(o[3]==='ال'&&o[4]==='مكتوب'&&o[5]===''&&o[6]==='كتب'&&o[7]==='مفعول','تحليل المكتوب: '+o.slice(3,8));
  ok(o[8]==='حرف جر','المبنيات: '+o[8]);ok(o[9]==='لاشيء','المبني بلا جذر');ok(o[10]==='مبني','المبني مع التشكيل');
  ok(o[11]==='[]','فارغ');ok(o[12]==='لاشيء','كلمة أقصر من الحد لا تحليل');ok(num(o[13])===1,'أقصى');
  ok(o[14]==='قال','حدّ معروف موثّق: الأجوف يُعاد بصورته السطحية لا بجذره (قول)');
  ok(o[15]==='كتب'&&o[16]==='كتب','التشكيل لا يغيّر التحليل');
}
// المعجم يقلب التعادل
{
  // «ثابت»: فاعل ثبت، أو ث+ابت... نختبر كلمة بتحليلين متقاربين: «كتبه» = كتب+ه أو (ك)+تبه
  const o=run(`
متغير ص = استورد("ضاد/نواة_صرف")
متغير أ = ص.حلّل("المكتوب"، لاشيء)
متغير ب = ص.حلّل("المكتوب"، {"معجم": {"كوب": صحيح}})
اطبع(أ[٠]["جذر"]) اطبع(ب[٠]["جذر"])
`);
  ok(o[0]==='كتب','بلا معجم: كتب');ok(o[1]==='كوب','المعجم يرفع الجذر الموجود فيه: '+o[1]);
}
// جذور النص
{
  const o=run(`
متغير ص = استورد("ضاد/نواة_صرف")
متغير ق = ص.جذور_النص("كتب الكاتب الكتاب والكتاب مكتوب ودرس الطالب"، ٢، لاشيء)
اطبع(ق[٠][٠]) اطبع(ق[٠][١]) اطبع(طول(ق))
`);
  ok(o[0]==='كتب'&&num(o[1])>=4&&num(o[2])===2,'جذور النص: '+o);
}
// الحتمية
{
  const src=`متغير ص = استورد("ضاد/نواة_صرف")\nمن_أجل (ك في ["يكتبون"، "المدرسة"، "تعاون"]) { من_أجل (أ في ص.حلّل(ك، لاشيء)) { اطبع(أ["جذر"] + أ["وزن"] + نص(أ["ثقة"])) } }`;
  ok(JSON.stringify(run(src))===JSON.stringify(run(src)),'الحتمية');
}
console.log(`nawa-morphology: ${pass} passed, ${fail} failed`);process.exit(fail?1:0);
