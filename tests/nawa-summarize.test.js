// التلخيص الاستخراجي: جمل حرفية من المصادر، الأقرب إلى السؤال، بلا تكرار، وبلا خلاصة إن لم يوجد ما يخص السؤال.
const path=require('path');const R=require(path.join(__dirname,'..','site','run.js'));
let pass=0,fail=0;const ok=(c,m)=>{if(c)pass++;else{fail++;console.log('FAIL',m)}};
const A='ابن سينا طبيب وفيلسوف فارسي من أشهر مؤلفاته القانون في الطب';
const B='ولد ابن سينا قرب بخارى سنة ٩٨٠ للميلاد';
const C='كان يحب الموسيقى والشعر والرياضة اليومية كثيرا';
const D='القانون في الطب كتاب ألفه ابن سينا وظل مرجعا قرونا طويلة';
const code=(q,h)=>'متغير ت = استورد("ضاد/نواة_تلخيص")\nمتغير م = [{"مصدر": "أ"، "نص": "عنوان قصير\\n\\n'+A+'. '+B+'. '+C+'."}، {"مصدر": "ب"، "نص": "'+A+'. '+D+'."}]\nمتغير ر = ت.لخّص(م، "'+q+'"'+(h?('، '+h):'')+')\nاطبع(ر["وُجد"])\nاطبع(طول(ر["جمل"]))\nمن_أجل (ج في ر["جمل"]) { اطبع(ج["مصدر"] + "|" + ج["نص"]) }'.replace(/\\n/g,'"+حرف(١٠)+"');
const run=(q,h)=>{const r=R.run(code(q,h),{maxMs:60000,maxSteps:1e9});return r.ok?r.out:['ERR '+r.error];};
let o=run('من هو ابن سينا');
ok(o[0]==='صحيح','وُجدت خلاصة: '+o[0]);
const lines=o.slice(2);
ok(lines.every(l=>{const t=l.split('|')[1];return t&&((A+'. '+B+'. '+C+'. '+D).includes(t));}),'كل جملة نقل حرفي من مصدرها');
ok(!lines.some(l=>l.includes('الموسيقى')),'جملة لا تخص السؤال لا تدخل');
ok(lines.filter(l=>l.includes('أشهر مؤلفاته')).length===1,'الجملة المكررة بين مصدرين تُذكر مرة واحدة');
ok(lines.some(l=>l.startsWith('ب|')||l.startsWith('أ|')),'مصدر كل جملة محفوظ');
o=run('ما الفوتوسنثيس');ok(o[0]==='خطأ'&&o[1]==='٠','لا خلاصة إن لم يوجد ما يخص السؤال');
o=run('من هو ابن سينا','٧٠');ok(o[1]==='١','الحد الأقصى للحروف يُحترم (جملة على الأقل)');
console.log('نجح',pass,'فشل',fail);process.exit(fail?1:0);
