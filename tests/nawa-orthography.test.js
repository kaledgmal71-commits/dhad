// فاحص الإملاء: يقترح ولا يفرض؛ لا يلمس الكلمات الصحيحة (ثلث، الرحمن…)؛ الغامض لا يُطبَّق إلا بطلب؛ المواضع صحيحة
const R=require('../site/run.js');
let pass=0,fail=0;const ok=(c,m)=>{if(c)pass++;else{fail++;console.log('FAIL',m)}};
const AR='٠١٢٣٤٥٦٧٨٩';const num=s=>Number(String(s).replace(/[٠-٩]/g,d=>AR.indexOf(d)));
const run=(src,o={})=>{const r=R.run(src,{maxMs:60000,maxSteps:400000000,...o});if(!r.ok)throw new Error(JSON.stringify(r).slice(0,300));return r.out};
const P='متغير ص = استورد("ضاد/نواة_إملاء")\n';
const fix=t=>run(P+`اطبع(ص.صحّح("${t}"))`)[0];
// حراسة الإيجابيات الكاذبة: كلمات صحيحة تبقى كما هي
for(const w of ['ثلث','ثلثان','الرحمن','الصلاة','الزكاة','علم','كتاب','إبراهيم','إسماعيل','الحياة','هذا','لكن','الله','قال حدثنا','ذلك','مسألة','إذا','شيء','موسى','حتى','على','إلى'])
  ok(fix(w)===w,'لا تغيير للصحيح: '+w+' → '+fix(w));
// تصحيحات غير غامضة
const cases=[['الصلوة','الصلاة'],['ابرهيم','إبراهيم'],['هاذا','هذا'],['ذالك','ذلك'],['ثلثة','ثلاثة'],['شئ','شيء'],['حتي','حتى'],['موسي','موسى'],['اذا','إذا'],['انسان','إنسان'],
  ['وذالك','وذلك'],['فهاذا','فهذا'],['قال ابرهيم في الصلوة','قال إبراهيم في الصلاة'],['الصَّلوة','الصلاة']];
for(const [a,b] of cases)ok(fix(a)===b,`${a} → ${b} (حصل ${fix(a)})`);
// الغامض يُقترح ولا يُطبَّق افتراضيًا
{
  const o=run(P+`
متغير ن = "ذهب علي الي السوق"
متغير ق = ص.اقترح(ن)
اطبع(طول(ق))
اطبع(ق[٠]["غامض"])
اطبع(ص.صحّح(ن))
اطبع(ص.طبّق(ن، ق، صحيح))
اطبع(ق[٠]["موضع"]) اطبع(ق[٠]["طول"]) اطبع(ق[٠]["أصل"]) اطبع(ق[٠]["اقتراح"])
اطبع(ق[١]["موضع"])
اطبع(نص(ص.اقترح("")))
اطبع(نص(ص.اقترح("123 abc ... ؟")))
اطبع(ص.صحّح(""))
`);
  ok(num(o[0])===2&&o[1]==='صحيح','اقتراحان غامضان');ok(o[2]==='ذهب علي الي السوق','الغامض لا يُطبَّق');
  ok(o[3]==='ذهب على إلى السوق','الكل يطبّق الغامض');ok(num(o[4])===4&&num(o[5])===3&&o[6]==='علي'&&o[7]==='على','موضع الكلمة وطولها');
  ok(num(o[8])===8,'موضع الاقتراح الثاني');ok(o[9]==='[]'&&o[10]==='[]'&&o[11]==='','نص فارغ أو بلا عربية');
}
// علامات الترقيم والتشكيل خارج الكلمة تُحفَظ
ok(fix('(الصلوة)، ثم ابرهيم.')==='(الصلاة)، ثم إبراهيم.','الترقيم يُحفظ: '+fix('(الصلوة)، ثم ابرهيم.'));
ok(fix('هَاذَا ثلث')==='هذا ثلث','المشكَّل يُستبدل ويفقد تشكيله: '+fix('هَاذَا ثلث'));
// الحتمية
ok(JSON.stringify(run(P+'اطبع(ص.صحّح("قال ابرهيم في الصلوة هاذا ثلث المال"))'))===JSON.stringify(run(P+'اطبع(ص.صحّح("قال ابرهيم في الصلوة هاذا ثلث المال"))')),'الحتمية');
console.log(`nawa-orthography: ${pass} passed, ${fail} failed`);process.exit(fail?1:0);
