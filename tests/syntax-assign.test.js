// بند ١-٩ من سجل النواقص: الإسناد المركّب الكامل والإسناد المتعدد. المطابقة مع مصرِّف ضاد في selfhost-parser/compiler.
const R = require('../site/run.js'); const api = R.api;
let pass = 0, fail = 0;
const check = (n, g, w) => { if (JSON.stringify(g) === JSON.stringify(w)) pass++; else { fail++; console.log('اختلاف:', n, g, w); } };
const run = src => { try { const c = api.compile(api.parse(src)); const o = []; const vm = new api.VM({ maxSteps: 1e6, maxMs: 2000, onPrint: l => o.push(String(l)) }); vm.run(c.mainChunkIndex, c.functionChunks); return o.join('|'); } catch (e) { return 'ERR ' + e.message; } };
check('**=', run('متغير أ = ٣\nأ **= ٢\nاطبع(أ)'), '٩');
check('//=', run('متغير أ = ١٧\nأ //= ٥\nاطبع(أ)'), '٣');
check('&=', run('متغير أ = 12\nأ &= 10\nاطبع(أ)'), '٨');
check('|=', run('متغير أ = 12\nأ |= 3\nاطبع(أ)'), '١٥');
check('^=', run('متغير أ = 12\nأ ^= 10\nاطبع(أ)'), '٦');
check('<<=', run('متغير أ = 3\nأ <<= 2\nاطبع(أ)'), '١٢');
check('>>=', run('متغير أ = 12\nأ >>= 2\nاطبع(أ)'), '٣');
check('??= يسند عند الفراغ', run('متغير أ = لاشيء\nأ ??= ٥\nاطبع(أ)'), '٥');
check('??= لا يسند عند وجود قيمة', run('متغير أ = ٧\nأ ??= ٥\nاطبع(أ)'), '٧');
check('??= صفر قيمة', run('متغير أ = ٠\nأ ??= ٥\nاطبع(أ)'), '٠');
check('مركّب على عنصر', run('متغير ق = [١، ٢]\nق[١] **= ٣\nق[٠] <<= ٤\nاطبع(ق)'), '[١٦، ٨]');
check('مركّب على مفتاح', run('متغير خ = {"ع": ٥}\nخ["ع"] //= ٢\nاطبع(خ["ع"])'), '٢');
check('القديم لم يتأثر', run('متغير أ = ٢\nأ += ٣\nأ *= ٢\nأ -= ١\nأ %= ٤\nاطبع(أ)'), '١');
check('<= و >= و << لم تتأثر', run('اطبع(٣ <= ٣، ٣ >= ٤، ١ << ٣)'), 'صحيح خطأ ٨');
check('تبديل', run('متغير أ = ١\nمتغير ب = ٢\nأ، ب = ب، أ\nاطبع(أ، ب)'), '٢ ١');
check('ثلاثة', run('متغير أ = ١\nمتغير ب = ٢\nمتغير ج = ٣\nأ، ب، ج = ج، أ، ب\nاطبع(أ، ب، ج)'), '٣ ١ ٢');
check('تبديل عناصر', run('متغير ق = [١، ٢، ٣]\nق[٠]، ق[٢] = ق[٢]، ق[٠]\nاطبع(ق)'), '[٣، ٢، ١]');
check('فيبوناتشي', run('متغير أ = ٠\nمتغير ب = ١\nمن_أجل (ع من ١ إلى ١٠) { أ، ب = ب، أ + ب }\nاطبع(أ)'), '٥٥');
check('داخل دالة', run('دالة ف(س، ص) { س، ص = ص، س\n ارجع [س، ص] }\nاطبع(ف(١، ٢))'), '[٢، ١]');
check('ثابت يُرفض', run('ثابت أ = ١\nمتغير ب = ٢\nأ، ب = ب، أ'), 'ERR لا يمكن إعادة إسناد الثابت «أ»');
check('عدد غير متساو', run('متغير أ = ١\nمتغير ب = ٢\nأ، ب = ١'), 'ERR السطر 3: عدد الأهداف (2) لا يساوي عدد القيم (1) في الإسناد المتعدد');
check('هدف غير صالح', run('متغير أ = ١\nأ، ٥ = ١، ٢'), 'ERR السطر 2: الطرف الأيسر للإسناد المتعدد يجب أن يكون متغيرًا أو عنصرًا بفهرس');
check('بلا يساوي', run('متغير أ = ١\nمتغير ب = ٢\nأ، ب'), 'ERR السطر 3: بعد الأهداف المتعددة يلزم علامة = ثم القيم');
console.log(`pass ${pass} fail ${fail}`); process.exit(fail ? 1 : 0);
