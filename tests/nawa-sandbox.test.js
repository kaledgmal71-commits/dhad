// منفذ العزل (ضاد/نواة_منفذ) و«نفّذ» بسقفيها
const path=require('path');
const R=require(path.join(__dirname,'..','site','run.js'));
let pass=0,fail=0;
const pre='متغير م = استورد("ضاد/نواة_منفذ")\nمتغير ع = استورد("ضاد/نواة_عقد")\n';
function t(name,body,expect){
  const r=R.run(pre+body,{maxMs:60000,maxSteps:1e9});
  const ok=expect===null?!r.ok:(r.ok&&JSON.stringify(r.out)===JSON.stringify(expect));
  if(ok)pass++;else{fail++;console.log('FAIL',name,JSON.stringify(r).slice(0,300),'expected',JSON.stringify(expect));}
}
