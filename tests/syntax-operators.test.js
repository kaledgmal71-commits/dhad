// بند ١-٥ من سجل النواقص: الأسّ ** والقسمة الصحيحة // والعمليات البتّية & | ^ ~ << >> (والمطابقة مع محلل ضاد في selfhost-parser/lexer).
const R = require('../site/run.js'); const api = R.api;
let pass = 0, fail = 0;
const check = (n, g, w) => { if (JSON.stringify(g) === JSON.stringify(w)) pass++; else { fail++; console.log('اختلاف:', n, g, w); } };
const run = src => { try { const c = api.compile(api.parse(src)); const o = []; const vm = new api.VM({ maxSteps: 1e6, maxMs: 2000, onPrint: l => o.push(String(l)) }); vm.run(c.mainChunkIndex, c.functionChunks); return o.join('|'); } catch (e) { return 'ERR ' + e.message; } };
const v = e => run('اطبع(' + e + ')').replace(/[٠-٩]/g, d => '٠١٢٣٤٥٦٧٨٩'.indexOf(d)).replace(/٫/g, '.');
const t = (e, w) => check(e, v(e), String(w));
t('2 ** 10', 1024); t('2 ** 3 ** 2', 512); t('-2 ** 2', -4); t('2 ** -1', 0.5); t('(-2) ** 3', -8); t('2 ** 0', 1);
t('7 // 2', 3); t('-7 // 2', -4); t('7 // -2', -4); t('7.5 // 2', 3); t('2 * 7 // 2', 7); t('7 // 2 * 2', 6);
t('6 & 3', 2); t('6 | 3', 7); t('6 ^ 3', 5); t('~5', -6); t('~-1', 0); t('1 << 10', 1024); t('-16 >> 2', -4); t('1 << 52 | 1', 4503599627370497); t('5 >> 70', 0); t('-5 >> 70', -1);
t('5 & 3 == 1', 'صحيح'); t('1 | 2 & 3 ^ 7', 5); t('1 + 2 << 3', 24); t('2 ** 2 ** 2 // 3', 5); t('~3 + 1', -3); t('- ~3', 4);
check('أسّ على قائمة', run('اطبع(قائمة ** ٢)').startsWith('ERR'), true);
check('قسمة صحيحة على صفر', run('اطبع(1 // 0)'), 'ERR السطر 1: قسمة على صفر');
check('صفر أسّ سالب', run('اطبع(0 ** -1)'), 'ERR السطر 1: قسمة على صفر');
check('أسّ جذر سالب', run('اطبع((-8) ** 0.5)'), 'ERR السطر 1: نتيجة العامل ** ليست عددًا حقيقيًّا');
check('أسّ كبير', run('اطبع(10 ** 400)'), 'ERR السطر 1: نتيجة العامل ** أكبر من أن تُمثَّل');
check('بتّي على كسر', run('اطبع(1.5 & 1)'), 'ERR السطر 1: العامل & يحتاج أعدادًا صحيحة');
check('بتّي على نص', run('اطبع("أ" | 1)'), 'ERR السطر 1: العامل | يحتاج أعدادًا صحيحة');
check('إزاحة خارج المدى', run('اطبع(1 << 60)'), 'ERR السطر 1: نتيجة العامل << خارج مدى الأعداد الصحيحة الآمن');
check('إزاحة سالبة', run('اطبع(1 << -1)'), 'ERR السطر 1: عدد الإزاحة لا يكون سالبًا');
check('الشرط المنطقي القديم سليم', run('اطبع(١ == ١ && ٢ == ٢، صحيح || خطأ)'), 'صحيح|صحيح'.replace('|', ' '));
check('تعليق # لا يختلط بـ //', run('اطبع(٨ // ٣) # تعليق // ثان'), '٢');
console.log(`pass ${pass} fail ${fail}`); process.exit(fail ? 1 : 0);
