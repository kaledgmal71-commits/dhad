// الواجهة الموحَّدة للتحليل الصرفي (tools/morph_all.js) وحزمة المتصفح (site/assets/nawa.morph.js) + جامد مع لواصق
const M=require('../tools/morph_all.js'),PC=require('../tools/morph_particles_clitic.js');let ok=0,bad=0;const t=(c,m)=>{if(c)ok++;else{bad++;console.log('فشل:',m)}};
// تحليل الطلب: إيجابية متنوعة
const POS=[['ما جذر كلمة يَكْتُبُونَهَا',1],['ما وزن «مَكْتُوبٌ»',1],['حلل صرفيا وَالْكَاتِبُ',1],['حلل كلمة قِيلَ',1],['جذر كلمة كَاتِبٌ',1],['ما هو وزن كِتَابُهُ',1],['من فضلك حلل صرفيا فِيهَا',1],['ما جذر «كَتَبَ يَكْتُبُ»',2],['التحليل الصرفي لكلمة مُسْتَخْرَجٌ',1]];
for(const [q,n] of POS){const w=M.parseRequest(q);t(w&&w.length===n,'طلب صرف: '+q+' ← '+JSON.stringify(w))}
// سلبية: لا تُلتقط
for(const q of ['حلل هذا الملف','حلل الملف المرفق','اكتب برنامجا يجمع قائمة','اشرح لي الإغلاقات','ما هي الدالة','أصلح الخطأ','حلل هذه الجملة','لخص النص','من أنت','ما وزن']){t(M.parseRequest(q)===null,'ليس طلب صرف: '+q)}
// نتائج صحيحة
const has=(w,f)=>M.analyzeWord(w).some(f);
t(has('يَكْتُبُونَهَا',a=>a.kind==='فعل'&&a.root==='كتب'&&a.enc==='هَا'),'فعل بلاصق');
t(has('وَالْكَاتِبُ',a=>a.kind==='اسم'&&a.root==='كتب'&&a.al&&a.pre==='وَ'),'اسم بسابقة وتعريف');
t(has('قَوْلِهِ',a=>a.kind==='اسم'&&a.root==='قول'&&a.enc),'مضاف بضمير هـِ');
t(has('ذُكِرَ',a=>a.kind==='فعل'&&a.root==='ذكر'&&/مجهول/.test(a.type)),'مبني للمجهول');
t(has('يُشْتَرَطُ',a=>a.kind==='فعل'&&a.root==='شرط'&&/مجهول/.test(a.type)),'مجهول مزيد');
t(has('يَعِدُ',a=>a.kind==='فعل'&&a.root==='وعد'),'مثال: يَعِدُ');
t(has('يَجِبْ',a=>a.kind==='فعل'&&a.root==='وجب'),'مجزوم مثال');
t(has('يَكُنْ',a=>a.kind==='فعل'&&a.root==='كون'),'مجزوم أجوف');
t(has('يَصِحَّ',a=>a.kind==='فعل'&&a.root==='صحح'),'مجزوم مضعّف');
t(has('عَلَيْهِ',a=>a.kind==='جامد'&&/ضمير/.test(a.type)),'جامد + ضمير');
t(has('لِمَا',a=>a.kind==='جامد'),'لِمَا');t(has('وَاللَّهِ',a=>a.kind==='جامد'&&/الجلالة/.test(a.type)),'اسم الجلالة');
t(has('مِنِّي',a=>a.kind==='جامد'),'مِنِّي');t(has('مَعَهُ',a=>a.kind==='جامد'),'مَعَهُ');t(has('إِنَّهُ',a=>a.kind==='جامد'),'إِنَّهُ');t(has('مِمَّا',a=>a.kind==='جامد'),'مِمَّا');
t(PC.analyze('هُرَيْرَةَ').length===0&&PC.analyze('كِتَابٌ').length===0,'غير جامد لا يُلتقط');
// صدق: كلمة غير مشكولة غير معروفة لا تُختلق
const a=M.answer('ما جذر كلمة كتاب');t(a&&a.includes('أضف التشكيل'),'غير مشكولة: '+a);
// الحزمة المبنية للمتصفح تطابق الأصل
const fs=require('fs'),path=require('path');global.window={};require(path.join(__dirname,'..','site','assets','nawa.morph.js'));
for(const q of ['ما جذر كلمة يَكْتُبُونَهَا','حلل صرفيا وَالْكَاتِبُ','ما وزن «مَكْتُوبٌ»','حلل كلمة قِيلَ','ما جذر كتاب'])t(window.NawaMorph.answer(q)===M.answer(q),'الحزمة = الأصل: '+q);
t(window.NawaMorph.answer('اكتب برنامجا')===null,'الحزمة: لا تلتقط غير الصرف');
console.log('نجح',ok,'فشل',bad);process.exit(bad?1:0);
