// التحقق من النص المنسوب: الموثَّق يبقى بنصه، وغير الموثَّق يُحذف، وغير المنسوب لا يُمَسّ.
const path=require('path');const R=require(path.join(__dirname,'..','site','run.js'));
let pass=0,fail=0;const ok=(c,m)=>{if(c)pass++;else{fail++;console.log('FAIL',m)}};
const SRC='حدثنا مالك عن نافع عن ابن عمر رضي الله عنهما أن رسول الله صلى الله عليه وسلم قال إنما الأعمال بالنيات وإنما لكل امرئ ما نوى. قال الله تعالى ولا تقربوا الزنا إنه كان فاحشة وساء سبيلا';
const REAL='قال رسول الله صلى الله عليه وسلم إنما الأعمال بالنيات وإنما لكل امرئ ما نوى';
const FAKE='قال رسول الله صلى الله عليه وسلم ألا إن العرق العظام سود من آثار الوضوء فمن أعان من أولياء الله';
const run=(t)=>{const r=R.run('متغير ق = استورد("ضاد/نواة_اقتباس")\nمتغير م = [{"مصدر": "الموطأ"، "نص": "'+SRC+'"}]\nمتغير ر = ق.نقّح("'+t+'"، م)\nاطبع(ر["نص"])\nاطبع(ر["منسوب"])\nاطبع(ر["موثّق"])\nاطبع(ر["محذوف"])',{maxMs:60000,maxSteps:1e9});return r.ok?r.out:['ERR '+r.error];};
let o=run('شرح عادي. '+REAL+'. خاتمة.');
ok(o[0].includes(REAL),'الحديث الموثَّق يبقى حرفيًّا');ok(o[3]==='٠'&&o[2]==='١','عدّ الموثَّق');
o=run('شرح. '+FAKE+'. خاتمة.');
ok(!o[0].includes('العرق'),'المختلَق يُحذف');ok(o[3]==='١','عدّ المحذوف');ok(o[0].includes('شرح')&&o[0].includes('خاتمة'),'غير المنسوب لا يُمس');
o=run('هذا كلام عام لا نسبة فيه ولا اقتباس');ok(o[1]==='٠'&&o[0].includes('كلام عام'),'نص بلا نسبة يمر كما هو');
o=run('قال تعالى ولا تقربوا الزنا');ok(o[3]==='٠','آية قصيرة موثَّقة تبقى');
o=run('قال تعالى ولا تقربوا الخمر');ok(o[3]==='١','آية قصيرة غير موجودة تُحذف');
o=run(REAL.replace('رسول الله صلى الله عليه وسلم','النبي ﷺ')+' ثم '+FAKE);ok(o[2]+o[3]!=='٠٠','النسبة بصيغة أخرى تُكشف');
o=run('«'+FAKE.slice(40)+'»');ok(o[3]==='١','اقتباس بين «» بلا علامة نسبة يُفحص');
console.log('نجح',pass,'فشل',fail);process.exit(fail?1:0);
