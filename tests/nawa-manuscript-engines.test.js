// محركا الرسم والمقابلة (منقولان من محركات «المُحَرِّر» مع تحسينات): هيكل الرسم بالموضع، التصحيف، المقابلة النقدية، وخاصية إعادة البناء
const R=require('../site/run.js');
let pass=0,fail=0;const ok=(c,m)=>{if(c)pass++;else{fail++;console.log('FAIL',m)}};
const AR='٠١٢٣٤٥٦٧٨٩';const num=s=>Number(String(s).replace(/[٠-٩]/g,d=>AR.indexOf(d)).replace(/٫/g,'.'));
const run=(src,o={})=>{const r=R.run(src,{maxMs:60000,maxSteps:400000000,...o});if(!r.ok)throw new Error(JSON.stringify(r).slice(0,300));return r.out};
// ---------- الرسم ----------
{
  const o=run(`
متغير ر = استورد("ضاد/نواة_رسم")
اطبع(ر.هيكل_الرسم("نبي"))
اطبع(ر.هيكل_الرسم("ببي"))
اطبع(ر.هيكل_الرسم("بن"))
اطبع(ر.هيكل_الرسم("بب"))
اطبع(ر.هيكل_الرسم("بق"))
اطبع(ر.هيكل_الرسم("بف"))
اطبع(ر.هيكل_الرسم("حدثنا"))
اطبع(ر.هيكل_الرسم("حَدَّثَنَا"))
اطبع(ر.هيكل_الرسم("جخح"))
اطبع(ر.هيكل_الرسم("ـــ"))
اطبع(ر.هيكل_الرسم(""))
اطبع(ر.تطابق_بلا_نقط("بني"، "نبي"))
اطبع(ر.تطابق_بلا_نقط("نبي"، "نبي"))
اطبع(ر.تطابق_بلا_نقط("جمل"، "حمل"))
اطبع(ر.تطابق_بلا_نقط("جمل"، "جمال"))
اطبع(ر.تطابق_بلا_نقط(""، "جمل"))
اطبع(ر.تطابق_بلا_نقط("يحيى"، "بحيي"))
اطبع(ر.مسافة_التحرير("كتاب"، "كتب"))
اطبع(ر.مسافة_التحرير(""، "abc"))
اطبع(ر.مسافة_التحرير("abc"، "abc"))
اطبع(ر.مسافة_التحرير("kitten"، "sitting"))
اطبع(ر.تشابه_الرسم("حدثنا"، "حدثتا"))
اطبع(ر.تشابه_الرسم(""، ""))
اطبع(ر.طبّع_للمقابلة("أَخْبَرَنَا مُؤْمِنٌ"))
اطبع(ر.طبّع_للمقابلة("مسألة"))
اطبع(ر.طبّع_للمقابلة("هدى"))
`);
  const [a,b,c,d,e,f,g,h,i,j,k,t1,t2,t3,t4,t5,t6,d1,d2,d3,d4,s1,s2,n1,n2,n3]=o;
  ok(a===b,'ن ب ي في الأول والوسط متطابقة: '+a+' '+b);
  ok(c!==d,'ن آخرًا تفترق عن ب آخرًا: '+c+' '+d);
  ok(e!==f,'ق آخرًا تفترق عن ف آخرًا');
  ok(g===h,'التشكيل لا يغيّر الهيكل');
  ok(i==='ححح','ج خ ح → ح: '+i);
  ok(j==='' && k==='','التطويل والفراغ → فارغ');
  ok(t1==='صحيح','بني/نبي تصحيف نقطي');ok(t2==='خطأ','الكلمة نفسها ليست تصحيفًا');
  ok(t3==='صحيح','جمل/حمل');ok(t4==='خطأ','جمل/جمال مختلفان');ok(t5==='خطأ','فارغ لا يطابق');
  ok(t6==='صحيح','يحيى/بحيي (ى آخرًا = ي آخرًا)');
  ok(num(d1)===1,'كتاب/كتب');ok(num(d2)===3,'فارغ/abc');ok(num(d3)===0,'متطابقان');ok(num(d4)===3,'kitten/sitting = 3 (قيمة معروفة)');
  ok(num(s1)===1,'حدثنا/حدثتا: ن قبل الألف متصلة فتطابق ت (هيكل واحد)');ok(num(s2)===1,'فارغان تشابههما ١');
  ok(n1==='اخبرنا مومن','تطبيع المقابلة: '+n1);ok(n2==='مساله','التاء المربوطة والهمزة: '+n2);ok(n3==='هدي','ى→ي: '+n3);
}
// ---------- المقابلة ----------
const P='متغير ق = استورد("ضاد/نواة_مقابلة")\n';
const show=(a,b,s)=>`
متغير ف = ق.قابل("${a}"، "${b}"، ${s?`"${s}"`:'لاشيء'})
اطبع(طول(ف))
من_أجل (ع في ف) { اطبع(ع["نوع"]) اطبع(ع["أصل"]) اطبع(ع["شاهد"]) اطبع(ع["موضع_أصل"]) }`;
const parse=o=>{const n=num(o[0]);const v=[];for(let i=0;i<n;i++)v.push({نوع:o[1+4*i],أصل:o[2+4*i],شاهد:o[3+4*i],موضع:num(o[4+4*i])});return v};
{
  let v=parse(run(P+show('حدثنا ابو بكر عن عاصم','حدثنا ابو بكر عن عاصم')));ok(v.length===0,'نسختان متطابقتان: لا فروق');
  v=parse(run(P+show('حدثنا أبو بكر','حدثنا ابو بكر')));ok(v.length===1&&v[0].نوع==='رسم','أبو/ابو رسم: '+JSON.stringify(v));
  v=parse(run(P+show('حدثنا اَبُو بَكْرٍ','حدثنا ابو بكر')));ok(v.length===0,'فرق التشكيل وحده لا يُعدّ فرقًا');
  v=parse(run(P+show('عن عياش الراوي','عن عباش الراوي')));ok(v.length===1&&v[0].نوع==='تصحيف'&&v[0].موضع===1,'عياش/عباش تصحيف: '+JSON.stringify(v));
  v=parse(run(P+show('قال زيد عمرو','قال عمرو زيد')));ok(v.length===1&&v[0].نوع==='قلب','تقديم وتأخير فرق واحد: '+JSON.stringify(v));
  v=parse(run(P+show('ذهب الولد الى المدرسة','ذهب الولد المدرسة جدا')));
  ok(v.length===2&&v[0].نوع==='سقط'&&v[0].أصل==='الى'&&v[1].نوع==='زيادة'&&v[1].شاهد==='جدا','سقط وزيادة: '+JSON.stringify(v));
  v=parse(run(P+show('كتب الكاتب رسالة','كتب الكاتب رساله طويلة')));ok(v.some(x=>x.نوع==='رسم'&&x.أصل==='رسالة')&&v.some(x=>x.نوع==='زيادة'),'رسم + زيادة: '+JSON.stringify(v));
  v=parse(run(P+show('الله اكبر','')));ok(v.length===2&&v.every(x=>x.نوع==='سقط'),'شاهد فارغ: سقط كامل');
  v=parse(run(P+show('','الله اكبر')));ok(v.length===2&&v.every(x=>x.نوع==='زيادة'),'أصل فارغ: زيادة كاملة');
  v=parse(run(P+show('','')));ok(v.length===0,'فارغان');
  v=parse(run(P+show('الجبل العالي','الحبل العالي')));ok(v.length===1&&v[0].نوع==='تصحيف','جبل/حبل: '+JSON.stringify(v));
  v=parse(run(P+show('فلان بن فلان','فلان بن علان')));ok(v.length===1&&v[0].نوع==='تحريف'||v[0].نوع==='إبدال','فلان/علان: '+JSON.stringify(v));
  v=parse(run(P+show('قدم الجيش','وصل الجيش')));ok(v.length===1&&v[0].نوع==='إبدال','إبدال لفظي: '+JSON.stringify(v));
  // كلمتان متماثلتان متجاورتان لا تُعدّان قلبًا
  v=parse(run(P+show('نعم نعم لا','نعم لا')));ok(v.length===1&&v[0].نوع==='سقط','تكرار لا يُعدّ قلبًا: '+JSON.stringify(v));
  // الرمز الافتراضي والمعطى
  const o=run(P+`متغير ف = ق.قابل("أ ب"، "أ ج"، لاشيء)\nاطبع(ف[٠]["رمز"])\nمتغير ف٢ = ق.قابل("أ ب"، "أ ج"، "س")\nاطبع(ف٢[٠]["رمز"])\nاطبع(ق.صغ_الحواشي(ف٢))\nاطبع(ق.صغ_الحواشي([]))\nاطبع(نص(ق.ملخص(ق.قابل("أ ب ج"، "أ ج د"، "س"))))`);
  ok(o[0]==='ب','الرمز الافتراضي ب');ok(o[1]==='س','الرمز المعطى');
  ok(/^\(١\) \[إبدال\] في \(س\): «ج» بدل «ب»\.$/.test(o[2]),'صياغة الحاشية: '+o[2]);
  ok(o[3]==='لا فروق بين النسختين.','حاشية فارغة');
}
// ---------- خاصية إعادة البناء: الأصل + الفروق = الشاهد (على ٤٠ حالة عشوائية بنواة ثابتة) ----------
{
  let seed=12345;const rnd=n=>{seed=(seed*1103515245+12345)%2147483648;return Math.floor(seed/2147483648*n)};
  const vocab='قال حدثنا أخبرنا عن ابن بن زيد عمرو بكر عياش عباش جبل حبل نبي بني يحيى الله رسول علم كتاب كتب مسجد مدينة'.split(' ');
  const cases=[];
  for(let c=0;c<40;c++){
    const L=2+rnd(9);const base=Array.from({length:L},()=>vocab[rnd(vocab.length)]);
    const w=base.slice();const edits=1+rnd(3);
    for(let e=0;e<edits;e++){const t=rnd(4);const p=rnd(w.length+1);
      if(t===0&&w.length)w.splice(Math.min(p,w.length-1),1);
      else if(t===1)w.splice(p,0,vocab[rnd(vocab.length)]);
      else if(t===2&&w.length)w[Math.min(p,w.length-1)]=vocab[rnd(vocab.length)];
      else if(w.length>1){const q=Math.min(p,w.length-2);[w[q],w[q+1]]=[w[q+1],w[q]]}}
    cases.push([base,w]);
  }
  let src=P;cases.forEach(([b,w],i)=>{src+=`\nمتغير ف${i} = ق.قابل("${b.join(' ')}"، "${w.join(' ')}"، "ب")\nاطبع("#")\nمن_أجل (ع في ف${i}) { اطبع(ع["نوع"]) اطبع(ع["أصل"]) اطبع(ع["شاهد"]) اطبع(ع["موضع_أصل"]) }`});
  const o=run(src,{maxMs:240000});
  const groups=[];o.forEach(x=>{if(x==='#')groups.push([]);else groups[groups.length-1].push(x)});
  let good=0;
  cases.forEach(([b,w],i)=>{
    const g=groups[i];const v=[];for(let k=0;k<g.length;k+=4)v.push({نوع:g[k],أصل:g[k+1],شاهد:g[k+2],موضع:num(g[k+3])});
    // إعادة البناء: نمرّ على كلمات الأصل ونطبّق الفروق عند مواضعها
    const out=[];let vi=0;let i2=0;
    const at=p=>v.filter(x=>x.موضع===p);
    for(let p=0;p<=b.length;p++){
      for(const x of at(p)){
        if(x.نوع==='زيادة')out.push(x.شاهد);
      }
      if(p===b.length)break;
      const rep=at(p).filter(x=>x.نوع!=='زيادة');
      if(rep.length){const x=rep[0];
        if(x.نوع==='سقط'){/* حُذفت */}
        else if(x.نوع==='قلب'){out.push(...x.شاهد.split(' '));p++;}
        else out.push(x.شاهد);}
      else out.push(b[p]);
    }
    if(out.join(' ')===w.join(' '))good++;else console.log('  إعادة بناء فاشلة',i,'\n   أصل:',b.join(' '),'\n   شاهد:',w.join(' '),'\n   ناتج:',out.join(' '),JSON.stringify(v));
  });
  ok(good===cases.length,`إعادة البناء ${good}/${cases.length}`);
  // الحتمية: تشغيلان بالمدخل نفسه يعطيان الخرج نفسه
  ok(JSON.stringify(run(src,{maxMs:240000}))===JSON.stringify(o),'الحتمية');
}
console.log(`nawa-manuscript-engines: ${pass} passed, ${fail} failed`);process.exit(fail?1:0);
