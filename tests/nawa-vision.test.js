// محرك الرؤية: النوى مقابل مرجع JS مستقل بالنوافذ المباشرة، وصفحة اصطناعية بإضاءة متدرجة (العتبة العامة تفشل وساوفولا تنجح)، وتقطيع السطور وحدود المتن والحمرة
const R=require('../site/run.js');
let pass=0,fail=0;const ok=(c,m)=>{if(c)pass++;else{fail++;console.log('FAIL',m)}};
const AR='٠١٢٣٤٥٦٧٨٩';const num=s=>Number(String(s).replace(/[٠-٩]/g,d=>AR.indexOf(d)).replace(/٫/g,'.'));
const A=n=>String(n).replace(/\d/g,d=>AR[d]).replace('.','.');
const run=(src,o={})=>{const r=R.run(src,{maxMs:120000,maxSteps:900000000,...o});if(!r.ok)throw new Error(JSON.stringify(r).slice(0,300));return r.out};
// ---------- (١) ساوفولا مقابل مرجع مباشر (بلا جداول تكاملية) ----------
{
  let seed=99;const rnd=n=>{seed=(seed*1103515245+12345)%2147483648;return Math.floor(seed/2147483648*n)};
  for(const [w,h,rad,k,rr] of [[12,9,2,0.2,128],[7,7,0,0.2,128],[10,6,15,0.34,100],[1,1,3,0.2,128],[16,5,1,0.05,64]]){
    const g=Array.from({length:w*h},()=>rnd(256));
    const ref=g.map((v,i)=>{const x=i%w,y=(i-x)/w;let s=0,q=0,c=0;for(let yy=Math.max(0,y-rad);yy<Math.min(h,y+rad+1);yy++)for(let xx=Math.max(0,x-rad);xx<Math.min(w,x+rad+1);xx++){const p=g[yy*w+xx];s+=p;q+=p*p;c++}
      const m=s/c,sd=Math.sqrt(Math.max(0,q/c-m*m));return v<=m*(1+k*(sd/rr-1))?1:0});
    const o=run(`متغير ص = نواة_ثنائي_ساوفولا([${g.join('،').replace(/\d+/g,A)}]، ${A(w)}، ${A(h)}، ${A(rad)}، ${A(k)}، ${A(rr)})\nمن_أجل (ق في ص) { اطبع(ق) }`);
    ok(o.map(num).join()===ref.join(),`ساوفولا ${w}×${h} نق=${rad} مطابق للمرجع`);
  }
}
// ---------- (٢) صفحة اصطناعية بإضاءة متدرجة ----------
// الخلفية تنزل من ٢٣٥ يسارًا إلى ١٠٠ يمينًا؛ أربعة سطور مداد (٨٠ درجة أغمق من خلفيتها) بارتفاع ٨ في الصفوف ٢٠..٢٧ و٤٥..٥٢ و٧٠..٧٧ و٩٥..١٠٢، بفجوات كلمات
const W=200,H=120;
const PAGE=`
متغير ع = ${W}
متغير ط = ${H}
متغير رمادي = []
متغير حقيقة = []
من_أجل (ص من ٠ إلى ط - ١) {
    من_أجل (س من ٠ إلى ع - ١) {
        متغير خلفية = ٢٣٥ - (٢٣٥ - ١٠٠) * س / (ع - ١)
        متغير حبر = خطأ
        إذا (س >= ٣٠ و س <= ١٧٠ و (س % ٢٥) < ٢٠) {
            إذا ((ص >= ٢٠ و ص <= ٢٧) أو (ص >= ٤٥ و ص <= ٥٢) أو (ص >= ٧٠ و ص <= ٧٧) أو (ص >= ٩٥ و ص <= ١٠٢)) { حبر = صحيح }
        }
        إذا (حبر) { أضف(رمادي، خلفية - ٨٠); أضف(حقيقة، ١) } وإلا { أضف(رمادي، خلفية); أضف(حقيقة، ٠) }
    }
}
متغير ر = استورد("ضاد/نواة_رؤية")
`;
{
  const o=run(PAGE+`
متغير س = ر.ثنّئ(رمادي، ع، ط، لاشيء)
متغير ع٢ = ر.عتبة_عامة(رمادي، ١٢٨)
متغير صح = ٠
متغير خطأ_س = ٠
متغير حبر_حقيقي = ٠
متغير صح٢ = ٠
من_أجل (ي من ٠ إلى ع * ط - ١) {
    إذا (حقيقة[ي] == ١) { حبر_حقيقي = حبر_حقيقي + ١; إذا (س[ي] == ١) { صح = صح + ١ }; إذا (ع٢[ي] == ١) { صح٢ = صح٢ + ١ } }
    إذا (حقيقة[ي] == ٠ و س[ي] == ١) { خطأ_س = خطأ_س + ١ }
}
اطبع(حبر_حقيقي) اطبع(صح) اطبع(خطأ_س) اطبع(صح٢)
متغير خطأ_ع = ٠
من_أجل (ي من ٠ إلى ع * ط - ١) { إذا (حقيقة[ي] == ٠ و ع٢[ي] == ١) { خطأ_ع = خطأ_ع + ١ } }
اطبع(خطأ_ع)
متغير سط = ر.سطور(س، ع، ط، لاشيء)
اطبع(طول(سط))
من_أجل (ق في سط) { اطبع(ق["بداية"]) اطبع(ق["نهاية"]) }
متغير حد = ر.حدود_المتن(س، ع، ط، لاشيء)
اطبع(حد["يسار"]) اطبع(حد["يمين"])
اطبع(ر.نسبة_الحبر(س) > ٠.١٣ و ر.نسبة_الحبر(س) < ٠.١٧)
متغير سط٢ = ر.سطور(ر.عتبة_عامة(رمادي، ١٢٨)، ع، ط، لاشيء)
اطبع(طول(سط٢))
`);
  const n=o.map(num);const [real,tp,fp,tpG,fpG,nl]=n;
  ok(tp/real>0.95,`ساوفولا تلتقط الحبر: ${tp}/${real}`);
  ok(fp/(W*H)<0.01,`ساوفولا خلفية خاطئة قليلة: ${fp}`);
  ok(fpG>W*H*0.1,`العتبة العامة تخطئ بالخلفية المعتمة (ضابط سلبي): ${fpG}`);
  ok(nl===4,'أربعة سطور: '+nl);
  const lines=[];for(let i=0;i<nl;i++)lines.push([n[6+2*i],n[7+2*i]]);
  const want=[[20,27],[45,52],[70,77],[95,102]];
  ok(lines.every((l,i)=>Math.abs(l[0]-want[i][0])<=1&&Math.abs(l[1]-want[i][1])<=1),'حدود السطور: '+JSON.stringify(lines));
  const left=n[6+2*nl],right=n[7+2*nl];
  ok(left>=28&&left<=34&&right>=165&&right<=172,`حدود المتن ${left}..${right}`);
  ok(o[8+2*nl]==="صحيح","نسبة الحبر ≈ الحقيقية (١٥٫٣٪)");
  ok(n[9+2*nl]!==4||true,'(معلومة) سطور العتبة العامة: '+n[9+2*nl]);
}
// ---------- (٣) الحمرة والرمادي ----------
{
  const o=run(`
متغير ر = استورد("ضاد/نواة_رؤية")
# بكسلان أحمر صريح، بكسل أسود، بكسل أبيض، بكسل برتقالي فاتح (إضاءة عالية)
متغير ص = [٢٠٠، ٣٠، ٣٠، ٢٥٥،  ٠، ٠، ٠، ٢٥٥،  ٢٥٥، ٢٥٥، ٢٥٥، ٢٥٥،  ٢٥٠، ٢٠٠، ١٠٠، ٢٥٥]
اطبع(نص(نواة_حمرة(ص، ٤، ١)))
اطبع(نص(ر.رمادي(ص، ٤، ١)))
اطبع(ر.نسبة_الحمرة(ص، ٤، ١))
اطبع(ر.نسبة_الحمرة([]، ٠، ٠))
اطبع(نص(ر.سطور([]، ٠، ٠، لاشيء)))
اطبع(نص(ر.حدود_المتن([٠، ٠، ٠، ٠]، ٢، ٢، لاشيء)))
`);
  ok(o[0]==='[١، ٠، ٠، ٠]'||o[0]==='[١,٠,٠,٠]'||/١.*٠.*٠.*٠/.test(o[0]),'قناع الحمرة: '+o[0]);
  const gr=o[1].replace(/[\[\]]/g,'').split(/[،,]\s*/).map(num);
  ok(gr[0]===Math.round(.299*200+.587*30+.114*30)&&gr[1]===0&&gr[2]===255,'الرمادي بمعاملات ITU: '+o[1]);
  ok(num(o[2])===0.25,'نسبة الحمرة ٢٥٪');ok(num(o[3])===0,'صورة فارغة');ok(o[4]==='[]','لا سطور في فارغ');ok(o[5]==='لاشيء','لا حدود لصفحة بيضاء');
}
// ---------- (٤) حدود وأخطاء ----------
{
  const bad=(src,m)=>{const r=R.run(src,{maxMs:20000});ok(!r.ok&&/نواة_/.test(JSON.stringify(r)),m+' '+JSON.stringify(r).slice(0,140))};
  bad('نواة_رمادي([١،٢،٣]، ١، ١)','طول RGBA خاطئ');
  bad('نواة_ثنائي_ساوفولا([١]، ٢، ١، ١، ٠.٢، ١٢٨)','طول الرمادي خاطئ');
  bad('نواة_ثنائي_ساوفولا([١]، ١، ١، -١، ٠.٢، ١٢٨)','نصف قطر سالب');
  bad('نواة_ثنائي_ساوفولا([١]، ١، ١، ١، ٠.٢، ٠)','مدى صفري');
  bad('نواة_مساقط([١]، ٢، ١)','طول المساقط خاطئ');
  bad('نواة_حمرة(٥، ١، ١)','ليست قائمة');
}
console.log(`nawa-vision: ${pass} passed, ${fail} failed`);process.exit(fail?1:0);
