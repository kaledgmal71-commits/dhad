// توليف نواة (ضاد/نواة_توليف): استرجاع + تحقق بالتنفيذ + إصلاح الأسماء؛ وتكامله مع المنسّق
const fs=require('fs'),path=require('path');
const R=require(path.join(__dirname,'..','site','run.js'));
let pass=0,fail=0;
const EX=[
 {معرف:'e/sum',عنوان:'مجموع الأعداد',وصف:'مجموع الأعداد من ١ إلى ٥',شيفرة:'متغير م = ٠\nمن_أجل (ي من ١ إلى ٥) { م = م + ي }\nاطبع(م)',ناتج:'١٥'},
 {معرف:'e/hello',عنوان:'ترحيب',وصف:'طباعة ترحيب بالعالم',شيفرة:'اطبع("مرحبا")',ناتج:'مرحبا'},
 {معرف:'e/typo',عنوان:'عداد التكرار',وصف:'عداد يزيد ثلاث مرات',شيفرة:'متغير عداد = ٠\nمن_أجل (ي من ١ إلى ٣) { عداد = عداد + ١ }\nاطبع(عدادد)',ناتج:'٣'},
 {معرف:'e/stale',عنوان:'قائمة الأسماء',وصف:'عرض قائمة أسماء',شيفرة:'اطبع("أ")',ناتج:'ب'},
 {معرف:'e/broken',عنوان:'حلقة ثقيلة',وصف:'حلقة ثقيلة مكسورة',شيفرة:'طالما (صحيح) { }',ناتج:'س'},
 {معرف:'e/multi',عنوان:'ثلاثة أسطر',وصف:'طباعة ثلاثة أسطر',شيفرة:'اطبع(١)\nاطبع(٢)\nاطبع(٣)',ناتج:'١\n٢\n٣'}
];
const pre='متغير ت = استورد("ضاد/نواة_توليف")\nمتغير ع = استورد("ضاد/نواة_عقد")\nمتغير ق = ت.ابنِ_قاعدة('+JSON.stringify(EX)+'،٣٠٠)\n';
function t(name,body,expect){
  const r=R.run(pre+body,{maxMs:120000,maxSteps:3e9});
  const ok=expect===null?!r.ok:(r.ok&&JSON.stringify(r.out)===JSON.stringify(expect));
  if(ok)pass++;else{fail++;console.log('FAIL',name,JSON.stringify(r).slice(0,300),'expected',JSON.stringify(expect));}
}
t('found','متغير ن = ت.ولّد(ق،"مجموع الأعداد")\nاطبع(ن["وُجد"]،ن["مصدر"]،ن["أُصلحت"])',['صحيح e/sum خطأ']);
t('code-returned','متغير ن = ت.ولّد(ق،"طباعة ترحيب")\nاطبع(ن["شيفرة"])',['اطبع("مرحبا")']);
t('multi-line-output','اطبع(ت.ولّد(ق،"طباعة ثلاثة أسطر")["مصدر"])',['e/multi']);
t('typo-fixed','متغير ن = ت.ولّد(ق،"عداد التكرار")\nاطبع(ن["وُجد"]،ن["أُصلحت"]،يحوي(ن["شيفرة"]،"اطبع(عداد)"))',['صحيح صحيح صحيح']);
t('mismatch-rejected','متغير ن = ت.ولّد(ق،"قائمة الأسماء")\nاطبع(ن["وُجد"]،ن["محاولات"][٠]["سبب"])',['خطأ المخرجات لا تطابق الناتج الموثَّق']);
t('runtime-fail-rejected','متغير ن = ت.ولّد(ق،"حلقة ثقيلة")\nاطبع(ن["وُجد"]،ن["محاولات"][٠]["نجح"])',['خطأ خطأ']);
t('not-found-honest','متغير ن = ت.ولّد(ق،"لعبة فضاء ثلاثية")\nاطبع(ن["وُجد"]،ن["شيفرة"]=="",طول(ن["محاولات"]))',['خطأ صحيح ٠']);
t('coverage-strict','اطبع(ت.ولّد(ق،"مجموع الأعداد الأولية الكبيرة")["وُجد"])',['خطأ']);
t('coverage-lenient','اطبع(ت.ولّد(ق،"مجموع الأعداد الأولية الكبيرة"،٣،٠٫٢)["وُجد"])',['صحيح']);
t('generic-words-ignored','اطبع(ت.ولّد(ق،"اكتب لي برنامج مجموع الأعداد")["مصدر"])',['e/sum']);
t('al-stripped','اطبع(ت.ولّد(ق،"الترحيب")["وُجد"])',['صحيح']);
t('attempt-limit','متغير ن = ت.ولّد(ق،"قائمة الأسماء حلقة ثقيلة"،١،٠٫٣)\nاطبع(طول(ن["محاولات"]))',['١']);
t('deterministic','اطبع(نص(ت.ولّد(ق،"مجموع الأعداد")) == نص(ت.ولّد(ق،"مجموع الأعداد")))',['صحيح']);
t('engine','ت.سجّل_المحرك()\nمتغير ن = ع.شغّل("توليف_شيفرة"،{"قاعدة": ق،"وصف": "طباعة ترحيب"})["نتيجة"]\nاطبع(ن["وُجد"]،ن["مصدر"])',['صحيح e/hello']);
t('err-base','ت.ولّد({}،"أ")',null);
t('err-desc','ت.ولّد(ق،"")',null);
t('err-limit','ت.ولّد(ق،"أ"،٠)',null);
t('err-examples','ت.ابنِ_قاعدة("س")',null);
t('err-example-shape','ت.ابنِ_قاعدة([{"معرف": "أ"}])',null);
// المنسّق: كتابة برنامج
const pre2='متغير س = استورد("ضاد/نواة_منسق")\nمتغير و٩ = استورد("ضاد/نواة_وحدة_ضاد")\nو٩.سجّل()\n';
t('orch-found',pre2+'متغير ب = س.نفّذ_الطلب("اكتب لي برنامجا بضاد مجموع الأعداد"،{"قاعدة": ق})\nاطبع(ب["نوع"]،ب["نتائج"]["توليف"]["مصدر"]،يحوي(ب["رد"]،"برنامج مُتحقَّق منه"))',['كتابة_برنامج e/sum صحيح']);
t('orch-not-found',pre2+'متغير ب = س.نفّذ_الطلب("ابنِ لي بضاد لعبة فضاء ثلاثية"،{"قاعدة": ق})\nاطبع(يحوي(ب["رد"]،"لم أجد برنامجًا موثوقًا"))',['صحيح']);
t('orch-no-base',pre2+'متغير ب = س.نفّذ_الطلب("اكتب لي برنامجا بضاد مجموع الأعداد"،{})\nمتغير ك = {}\nمن_أجل (ي في ب["خطة"]) { ك[ي["محرك"]] = ي["حالة"] }\nاطبع(ك["توليف_شيفرة"])',['تُخطّي']);
// قاعدة حقيقية من مدوّنة الموقع (تُتخطّى إن لم يُبنَ الموقع)
const CP=path.join(__dirname,'..','dist','ai','dhad-corpus.jsonl');
if(fs.existsSync(CP)){
  const rows=fs.readFileSync(CP,'utf8').trim().split('\n').map(l=>JSON.parse(l)).filter(r=>r.status==='ok'&&r.code&&r.output&&['example','lesson','explain','dictionary'].includes(r.source));
  const ex=rows.map(r=>({معرف:r.id,عنوان:r.title||r.id,وصف:r.instruction||'',شيفرة:r.code,ناتج:r.output}));
  const cases=[['الأعداد الأولية','example/primes'],['دوال مجهولة','lesson/closures'],['ترتيب قائمة','example/bubble']];
  const code='متغير ت = استورد("ضاد/نواة_توليف")\nمتغير ق = ت.ابنِ_قاعدة('+JSON.stringify(ex)+')\n'+cases.map(c=>'اطبع(ت.ولّد(ق،"'+c[0]+'")["مصدر"])').join('\n')+'\nاطبع(ت.ولّد(ق،"نظام تشغيل كامل")["وُجد"])';
  const r=R.run(code,{maxMs:300000,maxSteps:4e9});
  const want=cases.map(c=>c[1]).concat(['خطأ']);
  if(r.ok&&JSON.stringify(r.out)===JSON.stringify(want))pass++;else{fail++;console.log('FAIL real-corpus',JSON.stringify(r).slice(0,300));}
}
console.log('pass',pass,'fail',fail);
