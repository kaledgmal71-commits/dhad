// دراسة النص: الاختبار المبني من النص نفسه (الصحيح منقول، والفخاخ معلَّلة)، والتصحيح، وأسئلة وأجوبة، وتلخيص واختصار ونقاط، وفصلها عن البرمجة.
const path=require('path');const R=require(path.join(__dirname,'..','site','run.js'));
let pass=0,fail=0;const ok=(c,m)=>{if(c)pass++;else{fail++;console.log('FAIL',m)}};
const T='تأسست المدينة عام ١٩٥٠ على ضفة النهر الكبير. بلغ عدد سكانها ٢٠٠٠٠ نسمة في العام الأول. اشتهرت المدينة بزراعة القطن والقمح الجيد. يبلغ طول النهر ٣٠٠ كيلومتر تقريبا. أنشئت الجامعة الوطنية سنة ١٩٧٥ لخدمة الطلبة. تضم المكتبة المركزية مخطوطات نادرة كثيرة.';
const run=(src)=>{const r=R.run(src,{maxMs:60000,maxSteps:1e9});return r.ok?r.out:['ERR '+r.error];};
const head='متغير د = استورد("ضاد/نواة_دراسة")\nمتغير ت = د.اختبار("'+T+'"، ٦)\n';
// بنية الأسئلة
let o=run(head+`اطبع(طول(ت["أسئلة"]))
من_أجل (ق في ت["أسئلة"]) {
  اطبع(ق["نوع"] + "|" + ق["خيارات"][ق["صحيح"]] + "|" + ق["مصدر"] + "|" + نص(ق["صحيح"]) + "|" + نص(طول(ق["خيارات"])) + "|" + نص(طول(ق["أسباب"])))
}`);
ok(o[0]==='٦','ستة أسئلة من نص بست جمل: '+o[0]);
const qs=o.slice(1).map(l=>l.split('|'));
const norm=s=>s.replace(/[ًٌٍَُِّْ]/g,'');
ok(qs.every(q=>T.includes(q[2])),'مصدر كل سؤال جملة من النص');
ok(qs.filter(q=>q[0]!=='صح أو خطأ'&&q[0]!=='الصياغة الأمينة').every(q=>q[2].includes(q[1])),'جواب الرقم والإكمال منقول من جملة مصدره');
ok(qs.filter(q=>q[0]==='الصياغة الأمينة').every(q=>T.includes(q[1])),'الصياغة الأمينة الصحيحة وردت حرفيًّا في النص');
ok(new Set(qs.map(q=>q[3])).size>=3,'موضع الصحيح يتنوع');
ok(qs.every(q=>q[4]===q[5]),'سبب لكل خيار');
// الفخاخ مختلفة عن الصحيح ومتمايزة
o=run(head+`من_أجل (ق في ت["أسئلة"]) { إذا (ق["نوع"] != "صح أو خطأ") { اطبع(اربط(ق["خيارات"]، "|")) } }`);
ok(o.every(l=>{const a=l.split('|');return new Set(a).size===a.length;}),'خيارات كل سؤال متمايزة');
// أنواع الأسئلة المتعددة
o=run(head+`من_أجل (ق في ت["أسئلة"]) { اطبع(ق["نوع"]) }`);
ok(new Set(o).size>=3,'أنواع متنوعة: '+[...new Set(o)].join('،'));
// التصحيح: كل الصحيح
o=run(head+`متغير ج = []
من_أجل (ق في ت["أسئلة"]) { أضف(ج، ق["صحيح"]) }
متغير ر = د.صحّح(ت["أسئلة"]، ج)
اطبع(ر["درجة"])
اطبع(ر["من"])
اطبع(ر["نص"])`);
ok(o[0]==='٦'&&o[1]==='٦','تصحيح كل الإجابات الصحيحة');
ok(!o[2].includes('الفخ:'),'لا فخاخ تُذكر لمن أصاب');
// خطأ: يذكر الصحيح والفخ والاحتياط والمصدر
o=run(head+`متغير ج = []
من_أجل (ق في ت["أسئلة"]) { أضف(ج، (ق["صحيح"] + ١) % طول(ق["خيارات"])) }
متغير ر = د.صحّح(ت["أسئلة"]، ج)
اطبع(ر["درجة"])
اطبع(ر["نص"])`);
ok(o[0]==='٠','كل الإجابات خاطئة = صفر');
ok((o[1].match(/الفخ:/g)||[]).length===6&&(o[1].match(/الاحتياط:/g)||[]).length===6&&(o[1].match(/في النص:/g)||[]).length===6,'لكل خطأ: فخ واحتياط ومصدر');
ok(o[1].includes('الصحيح:'),'يذكر الصحيح');
// تحليل الإجابات
const pa=(s,n)=>run('متغير د = استورد("ضاد/نواة_دراسة")\nمتغير ج = د.حلّل_إجابات("'+s+'"، '+n+')\nإذا (ج == لاشيء) { اطبع("لا") } وإلا { اطبع(اربط(ج، ",")) }');
ok(pa('١ ب ٢ أ ٣ ج',3)[0]==='١,٠,٢','تحليل «١ ب ٢ أ ٣ ج»');
ok(pa('ب أ ج',3)[0]==='١,٠,٢','تحليل «ب أ ج» بالترتيب');
ok(pa('١ب ٢أ',3)[0]==='١,٠,-١','تحليل «١ب ٢أ» والمتروك بلا جواب');
ok(pa('اشرح لي هذا',3)[0]==='لا','الكلام العادي ليس أجوبة');
// نص قصير
o=run('متغير د = استورد("ضاد/نواة_دراسة")\nمتغير ت = د.اختبار("جملة قصيرة جدا."، ٥)\nاطبع(ت["وُجد"])');
ok(o[0]==='خطأ','نص قصير: لا اختبار');
// عبر المنسّق
const orch=(req,آخر)=>run('متغير م = استورد("ضاد/نواة_منسق")\nمتغير ر = م.نفّذ_الطلب("'+req.replace(/\n/g,'"+حرف(١٠)+"')+'"، {"آخر": '+(آخر||'{}')+'})\nاطبع(ر["نوع"])\nاطبع(ر["رد"])');
o=orch('اختبرني في هذا النص\n'+T);
ok(o[0]==='اختبار'&&o[1].includes('أ)')&&o[1].includes('_____'),'«اختبرني» + نص = اختبار: '+o[0]);
o=orch('حوّل هذا النص إلى أسئلة وأجوبة\n'+T);
ok(o[0]==='أسئلة_وأجوبة'&&o[1].includes('ج:')&&o[1].includes('المصدر:'),'أسئلة وأجوبة: '+o[0]);
o=orch('لخّص هذا النص\n'+T);
ok(o[0]==='تلخيص'&&T.includes(o[1].split('.')[0]),'تلخيص بجمل من النص: '+o[0]);
const o2=orch('اختصر هذا النص\n'+T);
ok(o2[0]==='اختصار'&&o2[1].length<=o[1].length,'الاختصار لا يزيد على التلخيص');
o=orch('نقاط هذا النص\n'+T);
ok(o[0]==='نقاط'&&o[1].startsWith('•'),'نقاط: '+o[0]);
// طلب بلا نص كاف أو برمجة لا يُعامل دراسة
o=orch('اكتب لي برنامجا يطبع مرحبا');
ok(o[0]!=='اختبار'&&o[0]!=='تلخيص','طلب البرمجة لا يُحوَّل لدراسة: '+o[0]);
o=orch('اختبرني');
ok(o[0]!=='اختبار','«اختبرني» بلا نص لا يولّد اختبارًا');
// تصحيح بعد اختبار قائم عبر السياق
o=run(head+`متغير م = استورد("ضاد/نواة_منسق")
متغير ر = م.نفّذ_الطلب("١ ب ٢ أ ٣ ج"، {"آخر": {"اختبار": ت["أسئلة"]}})
اطبع(ر["نوع"])
اطبع(ر["رد"])`);
ok(o[0]==='تصحيح_اختبار'&&o[1].includes('نتيجتك:'),'جواب بعد اختبار قائم يُصحَّح: '+o[0]);
console.log('نجح',pass,'فشل',fail);process.exit(fail?1:0);
