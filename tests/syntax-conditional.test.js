// بند ١-٦ من سجل النواقص: الشرط الثلاثي ? : ودمج الفراغ ?? والتسلسل الاختياري ?. (والمطابقة مع محلل ضاد في selfhost-*).
const R = require('../site/run.js'); const api = R.api;
let pass = 0, fail = 0;
const check = (n, g, w) => { if (JSON.stringify(g) === JSON.stringify(w)) pass++; else { fail++; console.log('اختلاف:', n, g, w); } };
const run = src => { try { const c = api.compile(api.parse(src)); const o = []; const vm = new api.VM({ maxSteps: 1e6, maxMs: 2000, onPrint: l => o.push(String(l)) }); vm.run(c.mainChunkIndex, c.functionChunks); return o.join('|'); } catch (e) { return 'ERR ' + e.message; } };
const P = 'متغير س = ٥\nمتغير ن = لاشيء\nمتغير م = {"أ": {"ب": ٣}، "ف": دالة(ع) { ارجع ع * ٢ }، "ق": [١، ٢]}\nمتغير ع = ٠\nدالة أثر(ز) { ع = ع + ١\n ارجع ز }\n';
const t = (e, w, pre) => check(e, run((pre || P) + 'اطبع(' + e + ')'), w);
t('س > ٣ ? "كبير" : "صغير"', 'كبير'); t('س < ٣ ? ١ : س < ٦ ? ٢ : ٣', '٢'); t('ن ? ١ : ٢', '٢'); t('س ? ٠ ? ١ : ٢ : ٣', '٢');
t('ن ?? ٧', '٧'); t('٠ ?? ٧', '٠'); t('خطأ ?? ٧', 'خطأ'); t('"" ?? ٧', ''); t('ن ?? ن ?? ٩', '٩'); t('(ن ?? ٣) + ١', '٤');
t('م?.أ?.ب', '٣'); t('م?.ز?.ب', 'لاشيء'); t('ن?.أ.ب.ج', 'لاشيء'); t('م?.ف(٤)', '٨'); t('م?.ز?.ف(٤)', 'لاشيء'); t('م?.["أ"]?.["ب"]', '٣'); t('م?.ق?.[١]', '٢'); t('م?.أ?.ب ?? ٠', '٣'); t('م?.ز?.ب ?? ٠', '٠');
t('س > ١ ? م?.أ?.ب : ٠', '٣');
// قصر الدائرة: الفرع غير المختار لا يُنفَّذ
check('ثلاثي لا ينفّذ الفرع الآخر', run(P + 'متغير ر = س ? أثر(١) : أثر(٢)\nاطبع(ع، ر)'), '١ ١');
check('دمج لا ينفّذ اليمين إن وُجدت قيمة', run(P + 'متغير ر = س ?? أثر(٢)\nاطبع(ع)'), '٠');
check('دمج ينفّذ اليمين مرة عند لاشيء', run(P + 'متغير ر = ن ?? أثر(٢)\nاطبع(ع، ر)'), '١ ٢');
check('تسلسل يقطع الوسائط بعد لاشيء', run(P + 'ن?.ز(أثر(١))\nاطبع(ع)'), '٠');
check('تسلسل غير اختياري يخطئ', run(P + 'اطبع(ن.أ)').startsWith('ERR'), true);
check('إسناد داخل فرع ثلاثي', run('متغير ك = ٠\nمتغير ي = ١ ? ك = ٥ : ك = ٦\nاطبع(ك)'), '٥');
check('معامل افتراضي بشرط', run('دالة ز(ص = ١ ? ٧ : ٨) { ارجع ص }\nاطبع(ز())'), '٧');
check('ثلاثي ناقص', run('اطبع(١ ? ٢)'), 'ERR السطر 1: كنت أنتظر «:» لكن وجدت «)»');
check('نقطة اختيارية بلا اسم', run('اطبع(م?.)').startsWith('ERR'), true);
check('الخريطة والنقطتان لا تلتبسان', run('متغير ك = ١\nاطبع({"أ": ك ? ٢ : ٣}["أ"])'), '٢');
console.log(`pass ${pass} fail ${fail}`); process.exit(fail ? 1 : 0);
