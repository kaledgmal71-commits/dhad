// الفك المقيّد بنحو ضاد ومكافأة التنفيذ
const R=require('../site/run.js');
let pass=0,fail=0;const ok=(c,m)=>{if(c)pass++;else{fail++;console.log('FAIL',m)}};
const D=s=>JSON.stringify(s);
const CORPUS=['دالة جمع(أ، ب) { ارجع أ + ب }','متغير س = ٥\nاطبع(س)','إذا (س > ٣) { اطبع("كبير") } وإلا { اطبع("صغير") }','من_أجل (ي من ١ إلى ٣) { اطبع(ي) }','طالما (س < ١٠) { س = س + ١ }'];
const PRE=`
متغير ر = استورد("ضاد/رياضيات")
متغير ع = استورد("ضاد/عيّنات")
متغير ز = استورد("ضاد/نواة_مجزئ")
متغير ف = استورد("ضاد/فك_مقيد")
متغير مج = ز.درّب(${D(CORPUS)}، ٣٠٠)
متغير ن٢ = ز.حجم(مج)
`;
function run(body,o={}){return R.run(PRE+body,{maxMs:o.ms||240000,maxSteps:9e10})}
// ---- حالة البداية
{const r=run(`اطبع(ف.حالة("دالة جمع(أ، ب) { ارجع أ + ب }"))\nاطبع(ف.حالة("دالة جمع(أ، ب) {"))\nاطبع(ف.حالة("متغير س = "))\nاطبع(ف.حالة("اطبع(\\"مر"))\nاطبع(ف.حالة("متغير س = )"))\nاطبع(ف.حالة("}"))\nاطبع(ف.حالة(""))`);
 ok(r.ok&&r.out.join('|')==='كامل|قابل|قابل|قابل|مرفوض|مرفوض|كامل',(r.ok?r.out.join('|'):JSON.stringify(r).slice(0,200))+' حالات الصياغة')}
// ---- منتج «أحادي»: يفضّل رموز هدف معيّن؛ المقيَّد يصل إلى برنامج كامل ويتوقف بـ eos
const ONEHOT=target=>`
متغير هدف = ز.رمّز_تسلسلا(مج، ${D(target)}، صحيح، خطأ)
متغير منتج = دالة(رموز) {
    متغير س = []
    من_أجل (ي في مدى(ن٢)) { أضف(س، -٥٠) }
    متغير صالح = (طول(رموز) <= طول(هدف))
    من_أجل (ي في مدى(طول(رموز))) { إذا (ي < طول(هدف) و رموز[ي] != هدف[ي]) { صالح = خطأ } }
    إذا (صالح و طول(رموز) < طول(هدف)) { س[هدف[طول(رموز)]] = ٥٠ }
    وإلا { س[ز.معرّف_خاص(مج، "<eos>")] = ٥٠ }
    ارجع س
}
`;
{const T='دالة جمع(أ، ب) { ارجع أ + ب }';const r=run(ONEHOT(T)+`متغير غ = ر.مولّد(١)\nمتغير خ = ف.ولّد(منتج، مج، "", ٦٠، غ، {"حرارة": ٠.٥})\nاطبع(خ["نص"] == ${D(T)})\nاطبع(خ["حالة"]، خ["سبب"])`);
 ok(r.ok&&r.out[0]==='صحيح'&&r.out[1]==='كامل eos','منتج أحادي يصل إلى الهدف '+(r.ok?r.out.join('|'):JSON.stringify(r).slice(0,300)))}
// ---- هدف يبدأ بـ«)» (مرفوض) : المقيَّد لا يخرجه
{const r=run(ONEHOT(') دالة')+`متغير غ = ر.مولّد(2)\nمتغير خ = ف.ولّد(منتج، مج، "", ١٥، غ، {})\nاطبع(خ["حالة"] != "مرفوض"، خ["نص"][٠] != ")")`);
 ok(r.ok&&r.out[0]==='صحيح صحيح','لا يخرج رمزًا يكسر الصياغة '+(r.ok?r.out.join('|'):JSON.stringify(r).slice(0,300)))}
// ---- eos مبكر مرفوض ما دام البرنامج ناقصًا
{const r=run(`
متغير منتج = دالة(رموز) {
    متغير س = []
    من_أجل (ي في مدى(ن٢)) { أضف(س، ٠) }
    س[ز.معرّف_خاص(مج، "<eos>")] = ١٠٠
    ارجع س
}
متغير غ = ر.مولّد(3)
متغير خ = ف.ولّد(منتج، مج، "دالة جمع(", ٨، غ، {})
اطبع(خ["سبب"] != "eos"، خ["حالة"] != "مرفوض")`);ok(r.ok&&r.out[0]==='صحيح صحيح','eos لا يُقبل في برنامج ناقص '+(r.ok?r.out.join('|'):JSON.stringify(r).slice(0,300)))}
// ---- سجلات عشوائية عدائية: المقيَّد لا يُنتج مرفوضًا أبدًا، وغير المقيَّد يُنتجه (ضابط سلبي)
{const r=run(`
متغير غ = ر.مولّد(٩)
متغير منتج = دالة(رموز) {
    متغير س = []
    من_أجل (ي في مدى(ن٢)) { أضف(س، ر.طبيعي(غ) * ٣) }
    ارجع س
}
متغير سيئ_مقيد = ٠
متغير سيئ_حر = ٠
من_أجل (ك في مدى(10)) {
    متغير خ = ف.ولّد(منتج، مج، "", ٢٠، غ، {})
    إذا (خ["حالة"] == "مرفوض") { سيئ_مقيد = سيئ_مقيد + ١ }
    متغير رموز = ز.رمّز_تسلسلا(مج، "", صحيح، خطأ)
    من_أجل (ي في مدى(٢٠)) { أضف(رموز، ع.عيّن(منتج(رموز)، غ)) }
    إذا (ف.حالة(ز.فكّ(مج، رموز)) == "مرفوض") { سيئ_حر = سيئ_حر + ١ }
}
اطبع(سيئ_مقيد، سيئ_حر)`,{ms:600000});
 if(!r.ok)ok(false,'عدائي '+JSON.stringify(r).slice(0,300));else{const [a,b]=r.out[0].split(' ');ok(a==='٠','المقيَّد لا يخرج مرفوضًا: '+a);ok(b!=='٠','ضابط سلبي: غير المقيَّد يخرج مرفوضًا ('+b+' من ١٠)')}}
// ---- المكافأة
{const r=run(`
اطبع(ف.مكافأة("اطبع(١ + ١)"، ["٢"]))
اطبع(ف.مكافأة("اطبع(١ + ١)"، ["٣"]))
اطبع(ف.مكافأة("اطبع(س_غير_معرف)"، ["٢"]))
اطبع(ف.مكافأة("متغير س = )"، ["٢"]))
اطبع(ف.مكافأة("متغير س = ١"، []))`);
 ok(r.ok&&r.out.join('|')==='١|٠٫٥|٠٫٣|٠|١','مكافأة التنفيذ '+(r.ok?r.out.join('|'):JSON.stringify(r).slice(0,200)))}
console.log('pass',pass,'fail',fail);process.exit(fail?1:0);
