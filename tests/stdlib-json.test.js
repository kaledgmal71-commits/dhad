// يحوّل نصًّا خامًا إلى تعبير ضاد آمن (الهروب في ضاد: \n \t \\ \" فقط، وغيرها عبر حرف())
function dh(txt){
  const parts=[];let cur='';
  const flush=()=>{if(cur!==''){parts.push('"'+cur+'"');cur='';}};
  for(const ch of txt){
    const c=ch.charCodeAt(0);
    if(ch==='\\')cur+='\\\\';
    else if(ch==='"')cur+='\\"';
    else if(ch==='\n')cur+='\\n';
    else if(ch==='\t')cur+='\\t';
    else if(c<32){flush();parts.push('حرف('+c+')');}
    else cur+=ch;
  }
  flush();
  return parts.length?parts.join(' + '):'""';
}
