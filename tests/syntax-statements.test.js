// بند ١-١٠ من سجل النواقص: نهاية الجملة والفاصلة المنقوطة. القاعدة الموثّقة:
// ١) الفاصلة المنقوطة اختيارية، وتجوز الجمل الفارغة (;;) وبعد الكتل.
// ٢) فاصل السطر ينهي الجملة إن بدأ السطر التالي بـ ( أو [ أو + أو - (خارج الأقواس)؛ وفي غير ذلك يستمر التعبير.
// ٣) داخل ( ) و [ ] وقيم الخرائط يبقى الاستمرار كما هو. المطابقة مع ضاد في selfhost-lexer/parser/compiler.
const R = require('../site/run.js'); const api = R.api;
let pass = 0, fail = 0;
const check = (n, g, w) => { if (JSON.stringify(g) === JSON.stringify(w)) pass++; else { fail++; console.log('اختلاف:', n, g, w); } };
const run = src => { try { const c = api.compile(api.parse(src)); const o = []; const vm = new api.VM({ maxSteps: 1e6, maxMs: 2000, onPrint: l => o.push(String(l)) }); vm.run(c.mainChunkIndex, c.functionChunks); return o.join('|'); } catch (e) { return 'ERR ' + e.message; } };
check('جملتان في سطر', run('اطبع(١) اطبع(٢)'), '١|٢');
check('منقوطات متتالية', run('اطبع(١); اطبع(٢);;'), '١|٢');
check('جمل فارغة', run(';;;\nاطبع(٣)'), '٣');
check('منقوطة بعد كتلة', run('إذا (صحيح) { اطبع(١) };\nاطبع(٢)'), '١|٢');
check('منقوطة داخل كتلة', run('دالة ف() { ;; اطبع(١); ; }\nف()'), '١');
check('سطر جديد قبل قوس ينهي الجملة', run('متغير أ = ١\n(٢)\nاطبع(أ)'), '١');
check('سطر جديد قبل قوس مربع', run('متغير أ = ١\n[٢، ٣]\nاطبع(أ)'), '١');
check('سطر جديد قبل ناقص', run('متغير أ = ٥\n-٢\nاطبع(أ)'), '٥');
check('سطر جديد قبل زائد جملة جديدة (ولا زائد أحادي)', run('متغير أ = ٥\n+٢\nاطبع(أ)'), 'ERR السطر 2: لم أفهم هذا الموضع — وجدت «+» حيث يُنتظر قيمة أو تعبير');
check('الاستمرار بعد عامل في آخر السطر', run('متغير أ = ٥ +\n٢\nاطبع(أ)'), '٧');
check('الاستمرار بنقطة', run('متغير ق = {"ن": {"ك": ٧}}\nاطبع(ق\n.ن\n.ك)'), '٧');
check('الاستمرار بـ و أو', run('متغير أ = صحيح\nمتغير ب = أ\nو خطأ\nاطبع(ب)'), 'خطأ');
check('داخل الأقواس يستمر الناقص', run('اطبع(٥\n-٢)'), '٣');
check('داخل الأقواس يستمر القوس', run('دالة ف() { ارجع دالة() { ارجع ٧ } }\nاطبع(ف()\n())'), '٧');
check('داخل القائمة يستمر الجمع', run('اطبع([١\n+ ٢، ٣])'), '[٣، ٣]');
check('قيمة خريطة متعددة الأسطر', run('متغير خ = {\n"أ": ١،\n"ب": ٢\n- ١\n}\nاطبع(خ["ب"])'), '١');
check('كتلة داخل استدعاء', run('دالة ع(ف) { ف() }\nع(دالة() {\nمتغير أ = ١\n(٢)\nاطبع(أ)\n})'), '١');
check('سلسلة بعد كتلة', run('متغير ف = دالة() { ارجع دالة() { ارجع ٩ } }\nاطبع(ف()())'), '٩');
check('قالب في سطر جديد جملة مستقلة', run('متغير أ = ١\nقالب"س{أ}"\nاطبع(أ)'), '١');
check('ارجع وقيمة على سطر لاحق كما كانت', run('دالة ف() { ارجع\n٥ }\nاطبع(ف())'), '٥');
console.log(`pass ${pass} fail ${fail}`); process.exit(fail ? 1 : 0);
