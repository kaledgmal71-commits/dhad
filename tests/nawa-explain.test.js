// شارح الشيفرة: الشرح مشتق من شجرة الصياغة الحقيقية (نواة_شجرة) لا من استرجاع نصوص
const R=require('../site/run.js');
let pass=0,fail=0;const ok=(c,m)=>{if(c)pass++;else{fail++;console.log('FAIL',m)}};
const run=(src)=>{const r=R.run(src,{maxMs:120000,maxSteps:2e9});if(!r.ok)throw new Error(JSON.stringify(r).slice(0,400));return r.out};
const lit=(c)=>'"'+c.replace(/"/g,'" + حرف(٣٤) + "').replace(/\n/g,'" + حرف(١٠) + "')+'"';
const sh=(c)=>run('متغير ش = استورد("ضاد/نواة_شرح")\nاطبع(ش.صغ(ش.اشرح('+lit(c)+')))').join('\n');
// المضيف: الشجرة
let o=run('متغير ش = نواة_شجرة("متغير س = ٥")\nاطبع(ش["kind"])\nاطبع(ش["statements"][٠]["kind"])\nاطبع(نواة_شجرة("إذا (")["خطأ"])');
ok(o[0]==='Program'&&o[1]==='VarDecl'&&/السطر 1/.test(o[2]),'نواة_شجرة: بنية وخطأ صياغة');
// الشرح
let t=sh('متغير س = ٥\nإذا (س > ٣) { اطبع(س) }');
ok(/يعرّف متغيرًا اسمه «س» ويضع فيه: ٥/.test(t),'متغير: '+t);
ok(/إن تحقق الشرط \(«س» أكبر من ٣\)/.test(t),'شرط');
ok(/يطبع: «س»/.test(t)&&/الناتج عند التشغيل:\s+٥/.test(t),'اطبع والناتج الفعلي: '+t);
t=sh('دالة مربع(ن) {\n    ارجع ن * ن\n}\nاطبع(مربع(٣))');
ok(/يعرّف دالة اسمها «مربع» تأخذ: ن/.test(t)&&/يُرجع «ن» \+ «ن»|يُرجع «ن» × «ن»/.test(t),'دالة وإرجاع: '+t);
ok(/٩/.test(t.split('الناتج عند التشغيل:')[1]),'الناتج ٩');
t=sh('من_أجل (ع من ١ إلى ٣) {\n    إذا (ع % ٢ == ٠) { اطبع(ع) } وإلا { توقف }\n}');
ok(/من ١ إلى ٣/.test(t)&&/باقي قسمة «ع» على ٢/.test(t)&&/وإلا/.test(t)&&/يقطع الحلقة/.test(t),'حلقة وباقي وإلا وتوقف: '+t);
t=sh('متغير ق = [١، ٢]\nمن_أجل (ه في ق) { اطبع(ه) }');
ok(/قائمة \(١، ٢\)/.test(t)&&/يمرّ على كل عنصر في «ق»/.test(t),'قائمة وتكرار على عناصرها');
// لا يشرح ما لم يُكتب: كل شرح مقابل سطر أو جملة فعلية
t=sh('متغير خ = {"أ": ١}');ok(/خريطة فيها ١ مدخلًا/.test(t),'خريطة');
// خطأ الصياغة يُعلَن
t=sh('إذا (');ok(/خطأ صياغة/.test(t)&&/السطر 1/.test(t),'خطأ صياغة: '+t);
// الناتج حقيقي لا مفبرك: شيفرة تطبع عددًا حُسب
t=sh('اطبع(٧ * ٦)');ok(/٤٢/.test(t.split('الناتج عند التشغيل:')[1]||''),'الناتج محسوب');
// عبر المنسّق: «اشرح» مع كتلة شيفرة
const S='متغير س = استورد("ضاد/نواة_منسق")\n';
const BT='" + حرف(٩٦) + حرف(٩٦) + حرف(٩٦) + "';
o=run(S+'متغير ب = س.نفّذ_الطلب("اشرح هذا الكود'+'" + حرف(١٠) + "'+BT+'" + حرف(١٠) + "اطبع(٧ * ٦)'+'" + حرف(١٠) + "'+BT+'"،{})\nاطبع(ب["نوع"])\nاطبع(ب["رد"])').join('\n');
ok(/^شرح/.test(o)&&/يطبع: ٧ × ٦/.test(o)&&/٤٢/.test(o),'المنسّق يوجّه «اشرح» + شيفرة إلى الشارح: '+o);
// سجل المحركات
o=run(S+'س.جهّز()\nمن_أجل (ك في ع.المحركات()) { اطبع(ك) }'.replace('ع.','استورد("ضاد/نواة_عقد").')).join(' ');
ok(o.includes('شرح_شيفرة'),'المحرك مسجَّل');
console.log(`nawa-explain: ${pass} passed, ${fail} failed`);process.exit(fail?1:0);
