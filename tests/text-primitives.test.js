// اختبار الدوال النصية الأولية: موضع (مع بداية) وموضع_أحد وعدّ_أحرف
const R = require('../site/run.js');
let pass = 0, fail = 0;
function t(name, code, want) {
  const r = R.run(code, {});
  const got = r.ok ? r.out.join('|') : 'خطأ: ' + r.error;
  if (got === want) pass++; else { fail++; console.log('فشل', name, 'المتوقع', want, 'الفعلي', got); }
}
t('موضع بدون بداية', 'اطبع(موضع("abcabc"، "c"))', '٢');
t('موضع مع بداية', 'اطبع(موضع("abcabc"، "c"، ٣))', '٥');
t('موضع غير موجود', 'اطبع(موضع("abc"، "z"، ١))', '-١');
t('موضع_أحد', 'اطبع(موضع_أحد("hello world"، "ow"))', '٤');
t('موضع_أحد مع بداية', 'اطبع(موضع_أحد("hello world"، "ow"، ٥))', '٦');
t('موضع_أحد غائب', 'اطبع(موضع_أحد("abc"، "xyz"))', '-١');
t('موضع_أحد عربي', 'اطبع(موضع_أحد("مرحبا بالعالم"، "ب"))', '٣');
t('موضع_أحد نص فارغ', 'اطبع(موضع_أحد(""، "a"))', '-١');
t('عدّ_أحرف', 'اطبع(عدّ_أحرف("banana"، "an"))', '٥');
t('عدّ_أحرف صفر', 'اطبع(عدّ_أحرف("banana"، "xyz"))', '٠');
t('عدّ_أحرف أحرف فارغة', 'اطبع(عدّ_أحرف("abc"، ""))', '٠');
t('خطأ النوع', 'اطبع(عدّ_أحرف(٥، "a"))', 'خطأ: السطر 1: عدّ_أحرف() تحتاج نصًا');
const bad = R.run('اطبع(موضع_أحد("a"، "a"، -١))', {});
if (!bad.ok) pass++; else { fail++; console.log('فشل: بداية سالبة يجب أن ترفض'); }
console.log(`pass ${pass} fail ${fail}`);
process.exit(fail ? 1 : 0);
